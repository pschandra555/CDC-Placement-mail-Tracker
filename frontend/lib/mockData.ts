const HOUR = 3600_000;
const anchor = () => Math.floor(Date.now() / HOUR) * HOUR;
const at = (hours: number) => new Date(anchor() + hours * HOUR).toISOString();
/** Event N days from today at a fixed local hour, e.g. day(9, 10) = 10 AM. */
const day = (n: number, hour: number) => {
  const d = new Date(anchor());
  d.setDate(d.getDate() + n);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
};

